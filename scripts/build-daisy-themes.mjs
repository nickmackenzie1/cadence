// Generates public/plugins/themes-daisy.js from daisyUI's theme files (MIT, https://daisyui.com).
// Usage: npm pack daisyui && tar -xzf daisyui-*.tgz && node scripts/build-daisy-themes.mjs package/theme
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-daisy-themes.mjs <daisyui>/theme'); process.exit(1); }
const SKIP = new Set(['light', 'dark', 'dracula', 'nord', 'cyberpunk']);   // generic, or Cadence has its own version

// oklch(L% C H) -> #rrggbb  (OKLab -> linear sRGB -> sRGB, clamped)
function oklch(str) {
  const m = /oklch\(\s*([\d.]+)%?\s+([\d.]+)\s+([\d.]+)/.exec(str); if (!m) return null;
  let L = +m[1]; if (str.includes('%')) L /= 100;
  const C = +m[2], h = (+m[3] * Math.PI) / 180, a = C * Math.cos(h), b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b, m_ = L - 0.1055613458 * a - 0.0638541728 * b, s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3, mm = m_ ** 3, s = s_ ** 3;
  const lin = [4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s];
  return '#' + lin.map(v => { v = v <= 0.0031308 ? 12.92 * v : 1.055 * Math.pow(Math.max(v, 0), 1 / 2.4) - 0.055; return Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0'); }).join('');
}
const mix = (a, b, t) => { const p = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16)); const A = p(a), B = p(b); return '#' + A.map((v, i) => Math.round(v * t + B[i] * (1 - t)).toString(16).padStart(2, '0')).join(''); };

const out = [];
for (const f of readdirSync(dir).filter(f => f.endsWith('.css')).sort()) {
  const id = f.replace('.css', ''); if (SKIP.has(id)) continue;
  const css = readFileSync(join(dir, f), 'utf8'), v = {};
  for (const m of css.matchAll(/--([\w-]+):\s*([^;]+);/g)) v[m[1]] = m[2].trim();
  const c = k => oklch(v['color-' + k] || '');
  const b1 = c('base-100'), b2 = c('base-200'), b3 = c('base-300'), tx = c('base-content');
  if (!b1 || !tx) continue;
  const dark = /dark/.test(css.match(/color-scheme:\s*(\w+)/)?.[1] || '');
  const NAMES = { cmyk: 'CMYK', lofi: 'Lo-fi', caramellatte: 'Caramel latte' };
  out.push({ id: 'daisy-' + id, name: NAMES[id] || id[0].toUpperCase() + id.slice(1), dark,
    vars: { '--bg': b2, '--panel': b1, '--side': mix(b2, b3, 0.5), '--text': tx, '--muted': mix(tx, b1, 0.62), '--faint': mix(tx, b1, 0.36), '--line': b3,
      '--hover': mix(tx, b1, 0.06), '--accent': c('primary'), '--on-accent': c('primary-content'), '--accent-soft': mix(c('primary'), b1, 0.16),
      '--danger': c('error'), '--danger-soft': mix(c('error'), b1, 0.14), '--ok': c('success'), '--client': c('warning'), '--client-soft': mix(c('warning'), b1, 0.18) },
    radius: { box: v['radius-box'] || '1rem', field: v['radius-field'] || '.5rem' }, border: v['border'] || '1px', depth: +(v['depth'] || 0) });
}
const js = `/* daisyUI themes (MIT, https://daisyui.com), mapped onto Cadence's tokens.
   Generated by scripts/build-daisy-themes.mjs: do not edit by hand. */
(() => {
  const T = ${JSON.stringify(out)};
  for (const t of T) window.CadenceThemes.register({
    id: t.id, name: t.name, category: 'daisyUI', tagline: (t.dark ? 'Dark' : 'Light') + ' · from daisyUI',
    vars: { ...t.vars, '--r': t.radius.box, '--shadow': t.depth ? '0 1px 2px rgba(0,0,0,.06),0 8px 24px rgba(0,0,0,.08)' : 'none' },
    preview: { r: t.radius.field },
    css: \`:skin .btn.primary{color:var(--on-accent)} :skin .btn,:skin .inp{border-radius:\${t.radius.field}} :skin .gl,:skin .stat,:skin .qa,:skin .dw-qa,:skin .pl-card,:skin .db-item:not(.bare),:skin .modal,:skin .th-card{border-radius:\${t.radius.box};border-width:\${t.border}}\`,
  });
})();
`;
writeFileSync(new URL('../public/plugins/themes-daisy.js', import.meta.url), js);
console.log(out.length + ' themes:', out.map(t => t.name).join(', '));
